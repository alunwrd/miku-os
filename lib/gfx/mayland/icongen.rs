// Turns an SVG icon into a table for a machine with no floating point
//
// Included by `lib/gfx/mayland/build.rs` with `#[path]`, as `fontgen.rs` is.
//
// The path is the input: `d="M19 21v-2a4 4 0 0 0-4-4H9..."` is parsed here,
// curves and arcs are flattened to line segments, and the output is polylines
// in the icon's 24-unit box. The machine scales them into the glyph's rectangle
// and strokes them; `Canvas::stroke` has the round caps these paths ask for,
// which also round the joins.
//
// Units: hundredths of a grid unit, so a `0 0 24 24` box is `0..2400` and
// `12.348` becomes `1235`, fitting `i16`. Stroke width likewise:
// `stroke-width="2"` is 200.

use std::path::Path;

/// The viewBox side in these units. Everything assumes lucide's square
/// `0 0 24 24` box; another viewBox is refused
const UNITS: f64 = 2400.0;

/// Largest distance of a segment from its curve, in grid units.
///
/// A sagitta, not an angle. Each segment is drawn as a round-capped stroke, so
/// segments shorter than a pixel pile caps on the same edge pixels and a
/// one-pixel line looks like three. This is a twelfth of the stroke's width,
/// under half a pixel at any drawn size
const TOLERANCE: f64 = 0.16;

/// The fewest and the most a single curve is ever broken into
const MIN_STEPS: usize = 2;
const MAX_STEPS: usize = 64;

/// Segments an arc of `radius` sweeping `rad` radians needs within `TOLERANCE`.
/// The sagitta of a chord subtending `t` is `r(1 - cos(t/2))`, so a tolerance
/// allows an angle of `2 * acos(1 - tol/r)`
fn steps_for(radius: f64, sweep: f64) -> usize {
    let r = radius.abs().max(1e-6);
    let per = if TOLERANCE >= r {
        std::f64::consts::PI
    } else {
        2.0 * (1.0 - TOLERANCE / r).clamp(-1.0, 1.0).acos()
    };
    ((sweep.abs() / per.max(1e-6)).ceil() as usize).clamp(MIN_STEPS, MAX_STEPS)
}

/// One `d` string, or one `<circle>`, flattened
type Poly = Vec<(i16, i16)>;

pub fn generate(dir: &Path, out_dir: &Path) {
    let mut names: Vec<String> = Vec::new();
    let mut bodies: Vec<Vec<Poly>> = Vec::new();

    let mut files: Vec<std::path::PathBuf> = match std::fs::read_dir(dir) {
        Ok(entries) => entries
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "svg"))
            .collect(),
        Err(_) => Vec::new(),
    };
    // Sorted, so the table is the same on two machines
    files.sort();

    for path in &files {
        let Ok(text) = std::fs::read_to_string(path) else { continue };
        let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("");
        match convert(&text) {
            Some(polys) if !polys.is_empty() => {
                println!("cargo:warning=icon '{stem}': {} strokes, {} points",
                         polys.len(), polys.iter().map(|p| p.len()).sum::<usize>());
                names.push(stem.to_string());
                bodies.push(polys);
            }
            _ => println!("cargo:warning=icon '{stem}' has nothing this can draw"),
        }
        println!("cargo:rerun-if-changed={}", path.display());
    }
    println!("cargo:rerun-if-changed={}", dir.display());

    std::fs::write(out_dir.join("icon_art.rs"), table(&names, &bodies))
        .expect("cannot write icon_art.rs");
}

fn table(names: &[String], bodies: &[Vec<Poly>]) -> String {
    let mut out = String::new();
    out.push_str("// Generated by lib/gfx/mayland/icongen.rs - do not edit\n\n");
    out.push_str(&format!(
        "/// The side of the box the points below are in\npub const ICON_UNITS: i32 = {};\n\n",
        UNITS as i32));
    out.push_str(
        "/// The stroke width the paths were drawn with, in the same units\n\
         pub const ICON_STROKE: i32 = 200;\n\n\
         /// One icon: polylines to be stroked, in order\n\
         pub struct IconArt {\n    pub name: &'static str,\n\
         \x20   pub strokes: &'static [&'static [(i16, i16)]],\n}\n\n");

    for (i, polys) in bodies.iter().enumerate() {
        for (j, poly) in polys.iter().enumerate() {
            out.push_str(&format!("static A{i}_{j}: [(i16, i16); {}] = [", poly.len()));
            for (k, (x, y)) in poly.iter().enumerate() {
                if k % 8 == 0 {
                    out.push_str("\n    ");
                }
                out.push_str(&format!("({x},{y}),"));
            }
            out.push_str("\n];\n");
        }
        out.push_str(&format!("static S{i}: [&[(i16, i16)]; {}] = [", polys.len()));
        for j in 0..polys.len() {
            out.push_str(&format!("&A{i}_{j},"));
        }
        out.push_str("];\n\n");
    }

    let longest = bodies.iter().flatten().map(|p| p.len()).max().unwrap_or(0);
    out.push_str(&format!(
        "/// The most points any one stroke below has. `ui` maps a stroke into\n\
         /// pixels through a stack array of this size, because that file has no\n\
         /// allocator - it is linked into the kernel as well\n\
         pub const ICON_MAX_POINTS: usize = {longest};\n\n"));

    out.push_str(&format!("pub static ICON_ART: [IconArt; {}] = [\n", names.len()));
    for (i, name) in names.iter().enumerate() {
        out.push_str(&format!("    IconArt {{ name: \"{name}\", strokes: &S{i} }},\n"));
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// The drawing for one icon, by the name of the file it came from\n\
         pub fn icon_art(name: &str) -> Option<&'static IconArt> {\n\
         \x20   ICON_ART.iter().find(|a| a.name == name)\n}\n");
    out
}

// The SVG, as much as these icons use

fn convert(svg: &str) -> Option<Vec<Poly>> {
    // Only this box; another would scale by the wrong number
    let vb = attr(svg, "viewBox")?;
    if vb.split_whitespace().collect::<Vec<_>>() != ["0", "0", "24", "24"] {
        return None;
    }

    let mut polys = Vec::new();
    for el in svg.split('<').skip(1) {
        let (tag, _) = el.split_once(|c: char| c.is_whitespace() || c == '>')?;
        match tag {
            "path" => {
                if let Some(d) = attr(el, "d") {
                    polys.extend(path(&d));
                }
            }
            "circle" => {
                let (cx, cy, r) = (num(el, "cx")?, num(el, "cy")?, num(el, "r")?);
                polys.push(ellipse(cx, cy, r, r));
            }
            "line" => {
                let (x1, y1) = (num(el, "x1")?, num(el, "y1")?);
                let (x2, y2) = (num(el, "x2")?, num(el, "y2")?);
                polys.push(quantise(&[(x1, y1), (x2, y2)]));
            }
            "rect" => {
                let (x, y) = (num(el, "x").unwrap_or(0.0), num(el, "y").unwrap_or(0.0));
                let (w, h) = (num(el, "width")?, num(el, "height")?);
                let rx = num(el, "rx").or_else(|| num(el, "ry")).unwrap_or(0.0);
                polys.push(round_rect(x, y, w, h, rx));
            }
            _ => {}
        }
    }
    Some(polys)
}

fn attr(el: &str, name: &str) -> Option<String> {
    let key = format!("{name}=\"");
    let at = el.find(&key)? + key.len();
    let end = el[at..].find('"')? + at;
    Some(el[at..end].to_string())
}

fn num(el: &str, name: &str) -> Option<f64> {
    attr(el, name)?.trim().parse().ok()
}

/// A `d` attribute, one polyline per subpath. `M m L l H h V v C c S s A a Z z`
fn path(d: &str) -> Vec<Poly> {
    let mut sc = Scan::new(d);
    let mut out: Vec<Poly> = Vec::new();
    let mut cur: Vec<(f64, f64)> = Vec::new();
    let (mut x, mut y) = (0.0f64, 0.0f64);
    let (mut sx, mut sy) = (0.0f64, 0.0f64);
    // The previous cubic's second control point, reflected by `S`
    let (mut px, mut py) = (0.0f64, 0.0f64);
    let mut cmd = ' ';

    loop {
        // A command letter, or the previous one repeated, as
        // `a10.75 10.75 0 0 1 19.876 0 1 1 0 0 1 0 .696` says "another arc"
        match sc.letter() {
            Some(l) => cmd = l,
            None if sc.more() && cmd != ' ' => {}
            _ => break,
        }
        let rel = cmd.is_ascii_lowercase();
        let (ox, oy) = if rel { (x, y) } else { (0.0, 0.0) };

        match cmd.to_ascii_uppercase() {
            'M' => {
                if cur.len() > 1 {
                    out.push(quantise(&cur));
                }
                cur.clear();
                x = ox + sc.num();
                y = oy + sc.num();
                sx = x;
                sy = y;
                cur.push((x, y));
                // A second pair after M is an implicit lineto
                cmd = if rel { 'l' } else { 'L' };
            }
            'L' => {
                x = ox + sc.num();
                y = oy + sc.num();
                cur.push((x, y));
            }
            'H' => {
                x = ox + sc.num();
                cur.push((x, y));
            }
            'V' => {
                y = oy + sc.num();
                cur.push((x, y));
            }
            'C' | 'S' => {
                let (c1x, c1y) = if cmd.to_ascii_uppercase() == 'C' {
                    (ox + sc.num(), oy + sc.num())
                } else {
                    // Reflect the last control point about the current point
                    (2.0 * x - px, 2.0 * y - py)
                };
                let (c2x, c2y) = (ox + sc.num(), oy + sc.num());
                let (nx, ny) = (ox + sc.num(), oy + sc.num());
                cubic(&mut cur, (x, y), (c1x, c1y), (c2x, c2y), (nx, ny));
                px = c2x;
                py = c2y;
                x = nx;
                y = ny;
            }
            'A' => {
                let rx = sc.num();
                let ry = sc.num();
                let rot = sc.num();
                let large = sc.flag();
                let sweep = sc.flag();
                let nx = ox + sc.num();
                let ny = oy + sc.num();
                arc(&mut cur, (x, y), rx, ry, rot, large, sweep, (nx, ny));
                x = nx;
                y = ny;
            }
            'Z' => {
                cur.push((sx, sy));
                x = sx;
                y = sy;
            }
            _ => break,
        }
        if !sc.more() {
            break;
        }
    }
    if cur.len() > 1 {
        out.push(quantise(&cur));
    }
    out
}

fn quantise(pts: &[(f64, f64)]) -> Poly {
    let mut out: Poly = Vec::with_capacity(pts.len());
    for &(x, y) in pts {
        let p = ((x * 100.0).round() as i16, (y * 100.0).round() as i16);
        // A finely flattened curve can put two samples on one hundredth; a
        // zero-length segment is skipped
        if out.last() != Some(&p) {
            out.push(p);
        }
    }
    out
}

fn cubic(out: &mut Vec<(f64, f64)>, p0: (f64, f64), c1: (f64, f64),
         c2: (f64, f64), p1: (f64, f64)) {
    // The control points' distance from the chord estimates the curvature
    let bend = ((c1.0 - p0.0).hypot(c1.1 - p0.1) + (c2.0 - c1.0).hypot(c2.1 - c1.1)
                + (p1.0 - c2.0).hypot(p1.1 - c2.1)) - (p1.0 - p0.0).hypot(p1.1 - p0.1);
    let steps = (((bend / TOLERANCE).sqrt() * 2.0).ceil() as usize)
        .clamp(MIN_STEPS, MAX_STEPS);
    for i in 1..=steps {
        let t = i as f64 / steps as f64;
        let u = 1.0 - t;
        let (a, b, c, d) = (u * u * u, 3.0 * u * u * t, 3.0 * u * t * t, t * t * t);
        out.push((a * p0.0 + b * c1.0 + c * c2.0 + d * p1.0,
                  a * p0.1 + b * c1.1 + c * c2.1 + d * p1.1));
    }
}

/// SVG's endpoint arc, sampled. Conversion to a center and two angles per the
/// specification, appendix F.6.5
#[allow(clippy::too_many_arguments)]
fn arc(out: &mut Vec<(f64, f64)>, p0: (f64, f64), rx: f64, ry: f64,
       rot_deg: f64, large: bool, sweep: bool, p1: (f64, f64)) {
    let (mut rx, mut ry) = (rx.abs(), ry.abs());
    if rx == 0.0 || ry == 0.0 || (p0.0 - p1.0).abs() + (p0.1 - p1.1).abs() < 1e-12 {
        out.push(p1);
        return;
    }
    let phi = rot_deg.to_radians();
    let (cos_p, sin_p) = (phi.cos(), phi.sin());

    let dx2 = (p0.0 - p1.0) / 2.0;
    let dy2 = (p0.1 - p1.1) / 2.0;
    let x1 = cos_p * dx2 + sin_p * dy2;
    let y1 = -sin_p * dx2 + cos_p * dy2;

    // Radii too small to reach are scaled up until they do, per the
    // specification
    let lam = (x1 * x1) / (rx * rx) + (y1 * y1) / (ry * ry);
    if lam > 1.0 {
        let s = lam.sqrt();
        rx *= s;
        ry *= s;
    }

    let num = (rx * rx * ry * ry - rx * rx * y1 * y1 - ry * ry * x1 * x1).max(0.0);
    let den = rx * rx * y1 * y1 + ry * ry * x1 * x1;
    let mut co = (num / den).sqrt();
    if large == sweep {
        co = -co;
    }
    let cxp = co * rx * y1 / ry;
    let cyp = -co * ry * x1 / rx;
    let cx = cos_p * cxp - sin_p * cyp + (p0.0 + p1.0) / 2.0;
    let cy = sin_p * cxp + cos_p * cyp + (p0.1 + p1.1) / 2.0;

    let ang = |ux: f64, uy: f64, vx: f64, vy: f64| -> f64 {
        let dot = ux * vx + uy * vy;
        let len = ((ux * ux + uy * uy) * (vx * vx + vy * vy)).sqrt();
        let mut a = (dot / len).clamp(-1.0, 1.0).acos();
        if ux * vy - uy * vx < 0.0 {
            a = -a;
        }
        a
    };
    let (ux, uy) = ((x1 - cxp) / rx, (y1 - cyp) / ry);
    let (vx, vy) = ((-x1 - cxp) / rx, (-y1 - cyp) / ry);
    let theta = ang(1.0, 0.0, ux, uy);
    let mut delta = ang(ux, uy, vx, vy);
    if !sweep && delta > 0.0 {
        delta -= std::f64::consts::TAU;
    } else if sweep && delta < 0.0 {
        delta += std::f64::consts::TAU;
    }

    let steps = steps_for(rx.max(ry), delta);
    for i in 1..=steps {
        let t = theta + delta * (i as f64 / steps as f64);
        let (ct, st) = (t.cos(), t.sin());
        out.push((cx + cos_p * rx * ct - sin_p * ry * st,
                  cy + sin_p * rx * ct + cos_p * ry * st));
    }
}

fn ellipse(cx: f64, cy: f64, rx: f64, ry: f64) -> Poly {
    let steps = steps_for(rx.max(ry), std::f64::consts::TAU);
    let mut pts = Vec::with_capacity(steps + 1);
    for i in 0..=steps {
        let t = std::f64::consts::TAU * i as f64 / steps as f64;
        pts.push((cx + rx * t.cos(), cy + ry * t.sin()));
    }
    quantise(&pts)
}

fn round_rect(x: f64, y: f64, w: f64, h: f64, r: f64) -> Poly {
    let r = r.min(w / 2.0).min(h / 2.0).max(0.0);
    let mut pts: Vec<(f64, f64)> = Vec::new();
    let corner = |pts: &mut Vec<(f64, f64)>, cx: f64, cy: f64, from: f64| {
        let steps = steps_for(r, std::f64::consts::FRAC_PI_2);
        for i in 0..=steps {
            let t = (from + 90.0 * i as f64 / steps as f64).to_radians();
            pts.push((cx + r * t.cos(), cy + r * t.sin()));
        }
    };
    pts.push((x + r, y));
    pts.push((x + w - r, y));
    corner(&mut pts, x + w - r, y + r, -90.0);
    pts.push((x + w, y + h - r));
    corner(&mut pts, x + w - r, y + h - r, 0.0);
    pts.push((x + r, y + h));
    corner(&mut pts, x + r, y + h - r, 90.0);
    pts.push((x, y + r));
    corner(&mut pts, x + r, y + r, 180.0);
    quantise(&pts)
}

/// Scanner over a `d` attribute. The grammar allows `19 21v-2` running a number
/// into the next command, `0 0 1 0-.696` running two numbers together on the
/// minus sign, and an arc's three flags with no separator
struct Scan<'a> {
    s: &'a [u8],
    i: usize,
}

impl<'a> Scan<'a> {
    fn new(s: &'a str) -> Scan<'a> {
        Scan { s: s.as_bytes(), i: 0 }
    }
    fn skip(&mut self) {
        while self.i < self.s.len() && (self.s[self.i].is_ascii_whitespace() || self.s[self.i] == b',') {
            self.i += 1;
        }
    }
    fn more(&mut self) -> bool {
        self.skip();
        self.i < self.s.len()
    }
    /// The next command letter, if the next thing is one
    fn letter(&mut self) -> Option<char> {
        self.skip();
        let c = *self.s.get(self.i)? as char;
        if c.is_ascii_alphabetic() {
            self.i += 1;
            Some(c)
        } else {
            None
        }
    }
    fn num(&mut self) -> f64 {
        self.skip();
        let start = self.i;
        if self.i < self.s.len() && (self.s[self.i] == b'-' || self.s[self.i] == b'+') {
            self.i += 1;
        }
        while self.i < self.s.len()
            && (self.s[self.i].is_ascii_digit() || self.s[self.i] == b'.')
        {
            self.i += 1;
        }
        // An exponent, which lucide does not write and a generated path might
        if self.i < self.s.len() && (self.s[self.i] | 0x20) == b'e' {
            self.i += 1;
            if self.i < self.s.len() && (self.s[self.i] == b'-' || self.s[self.i] == b'+') {
                self.i += 1;
            }
            while self.i < self.s.len() && self.s[self.i].is_ascii_digit() {
                self.i += 1;
            }
        }
        core::str::from_utf8(&self.s[start..self.i])
            .ok()
            .and_then(|t| t.parse().ok())
            .unwrap_or(0.0)
    }
    /// One arc flag: a single `0` or `1`, with no separator needed
    fn flag(&mut self) -> bool {
        self.skip();
        let c = self.s.get(self.i).copied().unwrap_or(b'0');
        self.i += 1;
        c == b'1'
    }
}
