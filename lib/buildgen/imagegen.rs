// Converts artwork to pixels at build time. Included with `#[path]`. Output is
// blue, green, red, alpha, premultiplied, so a blit is `src + dst*(1-a)`.
// Scaled here as well

use std::path::Path;

/// Writes `<name>_image.rs` and `<name>_image.bin` to `out_dir`. `size` is the
/// fitting square. `circle` masks to a round vignette with a soft edge. A
/// missing file gives an empty image
pub fn generate(src: &Path, out_dir: &Path, name: &str, size: u32, circle: bool) {
    let pixels = match load(src, size, circle) {
        Some(p) => p,
        None => {
            println!("cargo:warning={} not found, '{name}' will be empty", src.display());
            std::fs::write(out_dir.join(format!("{name}_image.bin")), []).unwrap();
            std::fs::write(
                out_dir.join(format!("{name}_image.rs")),
                table(name, 0, 0),
            )
            .unwrap();
            return;
        }
    };

    std::fs::write(out_dir.join(format!("{name}_image.bin")), &pixels).unwrap();
    std::fs::write(out_dir.join(format!("{name}_image.rs")), table(name, size, size)).unwrap();
    println!("cargo:rerun-if-changed={}", src.display());
}

fn load(src: &Path, size: u32, circle: bool) -> Option<Vec<u8>> {
    // Sniffs the format, since a file named .png here is a JPEG
    let img = image::ImageReader::open(src)
        .ok()?
        .with_guessed_format()
        .ok()?
        .decode()
        .ok()?
        .to_rgba8();
    let (sw, sh) = img.dimensions();
    if sw == 0 || sh == 0 {
        return None;
    }

    let mut out = Vec::with_capacity((size * size * 4) as usize);
    // Box filter: each destination pixel is the mean of the source pixels it
    // covers
    let sx = sw as f32 / size as f32;
    let sy = sh as f32 / size as f32;
    let r = size as f32 / 2.0;

    for y in 0..size {
        for x in 0..size {
            let (x0, x1) = ((x as f32 * sx) as u32, (((x + 1) as f32 * sx) as u32).min(sw));
            let (y0, y1) = ((y as f32 * sy) as u32, (((y + 1) as f32 * sy) as u32).min(sh));
            let (mut r_, mut g_, mut b_, mut a_, mut n) = (0u32, 0u32, 0u32, 0u32, 0u32);
            for py in y0..y1.max(y0 + 1) {
                for px in x0..x1.max(x0 + 1) {
                    let p = img.get_pixel(px.min(sw - 1), py.min(sh - 1)).0;
                    r_ += p[0] as u32;
                    g_ += p[1] as u32;
                    b_ += p[2] as u32;
                    a_ += p[3] as u32;
                    n += 1;
                }
            }
            let n = n.max(1);
            let (mut r8, mut g8, mut b8) = ((r_ / n) as u8, (g_ / n) as u8, (b_ / n) as u8);
            let mut a = (a_ / n) as u8;

            if circle {
                a = (a as f32 * circle_cov(x, y, r)) as u8;
            }

            // Premultiply
            let m = |c: &mut u8| *c = ((*c as u32 * a as u32 + 127) / 255) as u8;
            m(&mut r8);
            m(&mut g8);
            m(&mut b8);

            // Framebuffer order: blue first
            out.extend_from_slice(&[b8, g8, r8, a]);
        }
    }
    Some(out)
}

fn table(name: &str, w: u32, h: u32) -> String {
    let upper = name.to_uppercase();
    format!(
        "// Generated by imagegen.rs: premultiplied BGRA, framebuffer order\n\
         pub static {upper}_PIXELS: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \
         \"/{name}_image.bin\"));\n\
         pub const {upper}_W: usize = {w};\n\
         pub const {upper}_H: usize = {h};\n"
    )
}

/// Coverage of pixel `x, y` by a circle of radius `r` centered in a `2r`
/// square, with a 1.5-pixel feather. Shared with `qoigen`
pub fn circle_cov(x: u32, y: u32, r: f32) -> f32 {
    let dx = x as f32 + 0.5 - r;
    let dy = y as f32 + 0.5 - r;
    ((r - (dx * dx + dy * dy).sqrt()) / 1.5).clamp(0.0, 1.0)
}
