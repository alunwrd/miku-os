// QtQuick.Controls in the Basic style
//
// A Control has a `background` and `contentItem` as children, laid out by
// `scene/control.rs`: the background inside the insets, the content inside the
// padding. Style values: Button padding 6 and 2 more across, delegate 12,
// ScrollBar 2. Size is the larger of the background plus insets and the content
// plus padding. The style's own backgrounds and content items are not created.
//
// An AbstractButton is pressed and clicked like a MouseArea, unless an area
// above it takes the press (`input/pointer.rs`). A Control under the pointer is
// `hovered`.

