//! Reference snapshot of the NVIDIA display state
//!
//! Values were read from BAR0 while the monitor was active. The snapshot
//! contains the method blocks for the active display head and scanout window
//!
//! Methods unsupported by the hardware class return `0xbadf5040` and are
//! omitted from the snapshot
//!
//! The comparison reports differences between the reference state and our
//! driver's state

use super::pushbuf::{PushBuf, PushError};
use crate::drivers::gpu::nvidia::mmio::MmioRegion;

/// Initialize the assembly state from the currently armed core-channel state
///
/// EVO maintains separate assembly and active states for each method. Channel
/// allocation does not copy the active state into assembly, so an UPDATE may
/// apply stale values to methods that were not explicitly changed. This can
/// disrupt a display head configured by the firmware
///
/// Copy the readable armed methods into assembly before staging modifications.
/// Skip `UPDATE`, which triggers the state change, and omit write-only methods
/// that cannot be read back
pub fn adopt_armed_state(
    push: &mut PushBuf,
    bar0: &MmioRegion,
    head: u32,
) -> Result<(), PushError> {
    const M_UPDATE: u16 = 0x0200;

    let block = HEAD_BLOCK + head * HEAD_STRIDE;
    for &(off, _) in REF_HEAD.iter() {
        let v = bar0.read32(CORE_ARM_BASE + block + off as u32);
        push.mthd1(block + off as u32, v)?;
    }
    for &(off, _) in REF_CORE.iter() {
        if off == M_UPDATE {
            continue;
        }
        let v = bar0.read32(CORE_ARM_BASE + off as u32);
        push.mthd1(off as u32, v)?;
    }
    Ok(())
}

